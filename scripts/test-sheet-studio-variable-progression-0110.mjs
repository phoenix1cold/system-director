import assert from "node:assert/strict";
import fs from "node:fs";
const read=p=>fs.readFileSync(new URL(p,import.meta.url),"utf8");
const sheet=read("../module/sheets/character-sheet.mjs");
const header=read("../templates/actor/sheet-header.hbs");
const toolbox=read("../module/builder/toolbox-app.mjs");
const toolboxTpl=read("../templates/builder/toolbox.hbs");
const progression=read("../module/helpers/progression-app.mjs");
const classModel=read("../module/data/item-class.mjs");
const graph=read("../module/builder/formula-graph.mjs");
const executor=read("../module/helpers/button-executor.mjs");
const interactions=read("../module/helpers/interactables.mjs");
const formula=read("../module/helpers/formula-engine.mjs");
const controls=sheet.match(/controls:\s*\[([\s\S]*?)\]\s*\n\s*}/)?.[1]??"";
assert.doesNotMatch(controls,/Sheet Triggers|AI Bio/);
assert.match(header,/sd-sheet-icon-actions/);
assert.match(header,/data-action="openProgression"/);
assert.match(header,/data-action="openInteractions"/);
assert.match(header,/progressionLevel/);
assert.match(toolbox,/width:\s*520/);
assert.match(toolboxTpl,/sd-builder-iconbar/);
for(const action of ["openSheetGraph","openDocumentDatabase","openProgression","openInteractions"])assert.match(toolboxTpl,new RegExp(`data-action="${action}"`));
assert.match(progression,/levelVariableId/);
assert.match(progression,/readDatabaseValue\(this\._actor,this\._levelVariableId\)/);
assert.match(progression,/updates\[levelPath\]=lv\.level/);
assert.doesNotMatch(progression,/updates\["system\.advancement\.level"\]/);
assert.match(classModel,/path:\s+new StringField\(\{ initial: "", blank: true \}\)/);
assert.match(graph,/Public graphs are Database-variable only/);
assert.match(graph,/field\.type="select"/);
assert.match(graph,/pin\.type="value\.string"/);
assert.match(executor,/resolveVariablePaths\(action\)/);
assert.match(formula,/getValueDefinition\(path\)/);
assert.match(interactions,/Interaction Blueprint/);
assert.match(interactions,/Database-variable graph/);
console.log("PASS: icon-first Sheet Builder, restored variable-based Progression, cleaned menu, and variable-based Interactions/node paths.");
