import assert from "node:assert/strict";
import fs from "node:fs";
const read=n=>fs.readFileSync(new URL(`../${n}`,import.meta.url),"utf8");
const itemSheet=read("module/sheets/item-sheet.mjs");
const itemDoc=read("module/documents/item.mjs");
const ability=read("module/data/item-ability.mjs");
const inventory=read("module/data/item-inventory.mjs");
const cls=read("module/data/item-class.mjs");
const tree=read("module/data/item-skilltree.mjs");
const graph=read("module/builder/formula-graph.mjs");
const header=read("templates/item/parts/header.hbs");
const slots=read("templates/item/parts/slots.hbs");
const manifest=JSON.parse(read("system.json"));
for(const src of [ability,inventory,cls,tree]){assert.match(src,/values:\s*new ObjectField/);assert.match(src,/sdTriggerGraph:\s*new ObjectField/);}
const feature=ability.match(/export class FeatureData[\s\S]*/)?.[0]??"";
for(const token of ["customTabs","widgetFields","sdTriggerGraph"])assert.match(feature,new RegExp(token));
for(const action of ["openBuilder","openSheetTriggers","openDatabase","openEffectApplier","toggleEditMode","useItem"])assert.match(header,new RegExp(`data-action="${action}"`));
assert.match(header,/itemTypeIcon/);assert.match(header,/databaseCount/);
assert.match(itemSheet,/\["_sys_class","_sys_graph"\]/);
assert.match(itemSheet,/\["_sys_skilltree","_sys_graph"\]/);
assert.match(itemSheet,/Item Blueprint/);
assert.doesNotMatch(itemSheet,/On Click Graph<\/div>/);
assert.match(itemSheet,/_ensureCommonItemGraph/);
assert.match(itemSheet,/getValueDefinitions\(scope\)/);
assert.match(itemSheet,/grid-column:\$\{parentVS \? "1 \/ -1"/);
assert.match(itemSheet,/_wireSheetWidgetEvents/);
assert.match(itemSheet,/sdSheetWidgetEvent/);
assert.match(itemSheet,/elementKey/);
assert.match(itemDoc,/sdTriggerGraph/);assert.match(itemDoc,/_events\?\.onClick/);assert.match(itemDoc,/valueStoragePath/);
assert.match(graph,/itemSheetBlueprint=isSheetTrigger&&this\.doc\?\.documentName==="Item"/);
assert.match(graph,/ITEM BLUEPRINT — ALL WIDGETS & EVENTS/);
assert.doesNotMatch(slots,/hiddenFieldPairs/);
assert.ok(/^1\.(10\.([4-9]|\d{2,})|(1[1-9]|[2-9]\d)\.\d+)$/.test(manifest.version),`unexpected version ${manifest.version}`);
console.log("PASS: all standard Item types use scoped Database variables, icons and one common Item Blueprint.");
