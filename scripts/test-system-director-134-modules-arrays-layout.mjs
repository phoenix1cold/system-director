import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const root=path.resolve(import.meta.dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const manifest=JSON.parse(read("system.json"));
assert.equal(manifest.version,"1.3.5");
const runtime=read("module/helpers/node-runtime-api.mjs");
const executor=read("module/helpers/button-executor.mjs");
const engine=read("module/helpers/formula-engine.mjs");
const graph=read("module/builder/formula-graph.mjs");
const sheet=read("module/sheets/item-sheet.mjs");
assert.match(runtime,/registerNodeActionHandler/);
assert.match(runtime,/registerFormulaTokenResolver/);
assert.match(executor,/runNodeActionHandler/);
assert.match(engine,/resolveNodeFormulaToken/);
for(const node of ["item_array_inventory","item_array_slot","widget_value_array"]) assert.match(graph,new RegExp(`${node}:`));
for(const token of ["sdItemArrayInventory:","sdItemArraySlot:","sdWidgetArray:"]) assert.match(engine,new RegExp(token));
assert.match(engine,/_arrayFieldValue\(ref, path, doc\)/);
assert.match(graph,/startsWith.*endsWith/);
assert.match(sheet,/grid-template-columns:minmax\(190px,1fr\) minmax\(320px,1\.45fr\)/);
assert.match(sheet,/min-width:260px/);
console.log("PASS: System Director 1.3.5 module runtime, item arrays and progression layouts.");
